//! Generates `src/model/cdp/airwindows_catalog.toml` by asking the linked-in Airwindows
//! plugins about themselves.
//!
//! **Deliberately not a Python script**, unlike `scripts/convert_soundthread_catalog.py` and
//! `scripts/convert_praat_audiotools.py`. Those parse a foreign format — a JSON help file, a
//! Praat `form` block — and have to infer. Here the code is compiled into this very binary,
//! so the catalog is produced by *running* it: parameter names come from each plugin's own
//! `getParameterName`, and defaults from reading back `getParameter` immediately after
//! construction. Nothing is inferred and nothing can drift.
//!
//! What deliberately does *not* go in the catalog is the mapping from a normalized 0..1
//! parameter to the plugin's real units. That mapping exists only as arithmetic inside
//! `getParameterDisplay` — airwin2rack's `import.pl` regex-parses it and needs hardcoded
//! exceptions where the regex fails. We never guess: the dialog asks the live plugin for the
//! display string instead, so a field shows the plugin's own rendering of the current value.
//!
//! Usage:  cargo run --release --bin dump-airwindows-catalog > src/model/cdp/airwindows_catalog.toml

use airwindows_sys as ffi;

use std::fmt::Write as _;

/// Sample rate the plugins are constructed at purely to read their defaults back. Any rate
/// the base class accepts works — a default is a parameter value, not a filter coefficient,
/// so it does not vary with the rate.
const PROBE_RATE: u32 = 48_000;

fn main() {
    let mut out = String::new();
    let sha = submodule_sha();

    out.push_str(&format!(
        "# Generated by src/bin/dump-airwindows-catalog.rs from the Airwindows effect suite\n\
         # (MIT license, (c) Chris Johnson) as consolidated by airwin2rack (MIT license,\n\
         # (c) Paul Walker) -- see THIRD_PARTY_NOTICES.md.\n\
         # Source submodule third_party/airwin2rack at commit {sha}.\n\
         # Do not hand-edit; re-run the generator instead (./update-airwindows.sh). To add or\n\
         # override a process without touching this file, add a *.toml with the same\n\
         # [[process]] schema to $XDG_CONFIG_HOME/tui-wave/cdp/.\n"
    ));

    let mut emitted = 0usize;
    for (index, p) in ffi::plugins().enumerate() {
        let Some(inst) = ffi::Instance::new(index, PROBE_RATE) else {
            eprintln!("warning: {} would not instantiate; skipped", p.name);
            continue;
        };

        let description = p.description.trim();

        out.push_str("\n[[process]]\n");
        writeln!(out, "key = {}", quote(&key_for(p.name))).unwrap();
        // `<Category>/<Name>`, mirroring the Praat catalog's `<Dir>/<Script>.praat` exactly,
        // so `model::cdp::group` derives the browser group by the same leading-component
        // split it already uses rather than growing a second scheme.
        writeln!(out, "bin = {}", quote(&format!("{}/{}", p.category, p.name))).unwrap();
        writeln!(out, "title = {}", quote(p.name)).unwrap();
        out.push_str("category = \"airwindows\"\n");
        writeln!(out, "subcategory = {}", quote(p.category)).unwrap();
        writeln!(out, "short_description = {}", quote(&truncate(description, 160))).unwrap();
        writeln!(out, "description = {}", quote(description)).unwrap();
        out.push_str("input = \"wav\"\n");
        out.push_str("output = \"wav\"\n");
        // Both legs are handed over together — a plugin is never lane-split per channel, since
        // several are genuinely stereo-coupled (the reverbs, the mid/side processors) and
        // running those as two independent monos would be wrong rather than merely different.
        out.push_str("stereo_native = true\n");
        // Output is always exactly two channels, whatever went in.
        out.push_str("output_is_stereo = true\n");
        out.push_str("input_channels = \"mono_or_stereo\"\n");

        for i in 0..p.n_params {
            let name = inst.param_name(i);
            let label = inst.param_label(i);
            out.push_str("\n[[process.params]]\n");
            writeln!(out, "name = {}", quote(if name.is_empty() { "Param" } else { &name }))
                .unwrap();
            // The unit, when the plugin declares one. Most do not, and an empty label is the
            // norm rather than a gap — the value's real units show in the live display string.
            writeln!(out, "description = {}", quote(label.trim())).unwrap();
            out.push_str("automatable = false\n");
            out.push_str("kind = \"number\"\n");
            out.push_str("min = 0.0\n");
            out.push_str("max = 1.0\n");
            // 100 steps across the range: the same resolution a VST host's own automation
            // lane offers, and fine enough that no plugin's display string fails to move.
            out.push_str("step = 0.01\n");
            writeln!(out, "default = {:?}", inst.get_param(i)).unwrap();
            out.push_str("exponential = false\n");
            out.push_str("scale = \"plain\"\n");
        }
        emitted += 1;
    }

    print!("{out}");
    eprintln!("airwindows: emitted {emitted} of {} plugins", ffi::plugin_count());
}

/// `Density` -> `airwindows_density`. Airwindows names are CamelCase with digits
/// (`Air4`, `ADClip7`, `kPlateC`), so runs of capitals are kept together rather than each
/// getting its own underscore — `ADClip7` becomes `adclip7`, not `a_d_clip7`.
fn key_for(name: &str) -> String {
    let mut out = String::from("airwindows_");
    let chars: Vec<char> = name.chars().collect();
    for (i, &c) in chars.iter().enumerate() {
        let prev_lower = i > 0 && (chars[i - 1].is_lowercase() || chars[i - 1].is_ascii_digit());
        if c.is_uppercase() && prev_lower {
            out.push('_');
        }
        out.extend(c.to_lowercase());
    }
    out
}

fn truncate(s: &str, max: usize) -> String {
    if s.chars().count() <= max {
        return s.to_string();
    }
    s.chars().take(max).collect()
}

/// A TOML basic string. Airwindows descriptions are prose written by one person and contain
/// quotes and backslashes often enough to matter.
fn quote(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04X}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The submodule commit the catalog was generated against, recorded in the header for the
/// same reason the Praat catalog records its own: Airwindows plugins are matched to catalog
/// entries by *registry order and parameter index*, so a submodule bump without a regenerate
/// would silently point entries at the wrong parameters.
fn submodule_sha() -> String {
    std::process::Command::new("git")
        .args(["-C", "third_party/airwin2rack", "rev-parse", "HEAD"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "unknown".to_string())
}
