//! CDP's own process grouping, derived from a process's binary rather than stored per entry.
//!
//! The group names and their membership are taken directly from CDP's two index pages —
//! `cgroundx.htm` (time domain) and `cspecndx.htm` (spectral) — so a group heading here reads
//! exactly as it does in CDP's documentation, its printed manuals, and the CDP GUI. That is the
//! whole point of grouping this way: someone reading CDP's own material about `blur scatter`
//! finds it under BLUR here too, with no translation step.
//!
//! This replaced a hand-assigned `ProcessDef.subcategory` taxonomy that grouped by *sonic
//! function* instead (`distort`, `texture`, `filter`, `envelope`, …). That scheme read better to
//! a newcomer, but it had two costs that decided the switch: it disagreed with every piece of
//! CDP documentation a user might consult, and its buckets were badly lopsided (`texture` alone
//! held 82 of 407 processes while `amplitude` and `channels` held one each). Note the CDP
//! scheme does not fully fix lopsidedness — DISTORT is 83 processes — but that bucket is at
//! least coherent and is what CDP itself calls it.
//!
//! **Derived, never stored.** The mapping is a pure function of `bin` (plus `category`, for the
//! two binaries that exist in both domains), so it needs no new catalog field. That matters
//! because `catalog.toml` is machine-generated by `scripts/convert_soundthread_catalog.py` and
//! carries a "do not hand-edit" header — a per-entry group column would be silently reverted by
//! the next converter run, and 407 hand-edits would be unreviewable besides. A table here is
//! also the only place a CDP docs correction has to land.

use super::def::{Category, ProcessDef};

/// A CDP group heading plus the domain whose index page documents it. Domain is carried
/// because the browser navigates domain-first, and because two binaries (`fractal`, `repitch`)
/// legitimately appear in both.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct CdpGroup {
    pub category: Category,
    pub name: &'static str,
}

