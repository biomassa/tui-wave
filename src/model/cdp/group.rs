/// The CDP group `def` belongs to, or `None` if its binary is not in the table — which is a
/// catalog/table disagreement rather than a real state, and is what
/// `every_catalog_process_maps_to_a_cdp_group` exists to prevent.
pub fn cdp_group(def: &ProcessDef) -> Option<CdpGroup> {
    // `fractal` is two unrelated programs sharing a name: `fractal wave` (time domain, filed
    // under DISTORT) and `fractal spectrum` (spectral, filed under SPECNU). The domain is what
    // tells them apart — there is no single answer keyed on the binary alone.
    // A Praat entry's group is its script's directory, not a binary name — there is only one
    // Praat binary and it tells you nothing about what the script does.
    if def.category == Category::Praat {
        let dir = def.bin.split('/').next()?;
        let name = PRAAT_DIRS.iter().find(|(d, _)| *d == dir).map(|(_, group)| *group)?;
        return Some(CdpGroup { category: def.category, name });
    }
    let name = if def.bin == "fractal" {
        match def.category {
            Category::Time => "DISTORT",
            Category::Pvoc => "SPECNU",
            Category::Praat => unreachable!("handled above"),
        }
    } else {
        let table = match def.category {
            Category::Time => TIME_BINS,
            Category::Pvoc => PVOC_BINS,
            Category::Praat => unreachable!("handled above"),
        };
        table.iter().find(|(bin, _)| *bin == def.bin).map(|(_, group)| *group)?
    };
    Some(CdpGroup { category: def.category, name })
}

/// Every group defined for `category`, in CDP's own listing order.
pub fn groups_for(category: Category) -> &'static [&'static str] {
    match category {
        Category::Time => TIME_GROUPS,
        Category::Pvoc => PVOC_GROUPS,
        Category::Praat => PRAAT_GROUPS,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::cdp::CdpCatalog;

    /// The table must cover the whole catalog. A process with no group would simply vanish from
    /// the browser's group filter — visible only under "All" — which is exactly the kind of
    /// silent omission that is hard to notice by hand across 400+ entries.
    #[test]
    fn every_catalog_process_maps_to_a_cdp_group() {
        let (catalog, _) = CdpCatalog::load(None);
        let missing: Vec<_> = catalog
            .processes
            .iter()
            .filter(|p| cdp_group(p).is_none())
            .map(|p| format!("{} (bin {}, {:?})", p.key, p.bin, p.category))
            .collect();
        assert!(missing.is_empty(), "processes with no CDP group: {missing:#?}");
    }

    /// Every group a process resolves to must be one the browser actually offers for that
    /// domain, or picking that group in the UI would show an empty list.
    #[test]
    fn every_resolved_group_is_listed_for_its_domain() {
        let (catalog, _) = CdpCatalog::load(None);
        for p in &catalog.processes {
            let group = cdp_group(p).expect("covered by every_catalog_process_maps_to_a_cdp_group");
            assert!(
                groups_for(group.category).contains(&group.name),
                "{} resolves to {} which is not listed for {:?}",
                p.key,
                group.name,
                group.category
            );
        }
    }

    /// The reverse direction: a listed group with nothing in it is a dead row in the UI. This
    /// catches a group surviving in the lists after every process using it was removed.
    #[test]
    fn every_listed_group_has_at_least_one_process() {
        let (catalog, _) = CdpCatalog::load(None);
        for category in [Category::Time, Category::Pvoc] {
            for name in groups_for(category) {
                let count = catalog
                    .processes
                    .iter()
                    .filter(|p| cdp_group(p) == Some(CdpGroup { category, name }))
                    .count();
                assert!(count > 0, "{name} ({category:?}) is listed but empty");
            }
        }
    }

    /// `fractal` is the one binary whose group genuinely depends on the domain; pin it so a
    /// future table edit can't collapse the two into one answer.
    #[test]
    fn fractal_resolves_differently_per_domain() {
        let (catalog, _) = CdpCatalog::load(None);
        for p in catalog.processes.iter().filter(|p| p.bin == "fractal") {
            let expected = match p.category {
                Category::Time => "DISTORT",
                Category::Pvoc => "SPECNU",
                Category::Praat => unreachable!("no Praat entry has bin `fractal`"),
            };
            assert_eq!(cdp_group(p).unwrap().name, expected, "{}", p.key);
        }
    }
}
